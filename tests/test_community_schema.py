FROZEN_M3_FIXTURE = Path(__file__).parent / "fixtures" / "m3-schema2.sqlite3.gz"
M3_INITIAL_DIGEST = "18de2acac2c18c2376d8b494765a47a4a0c00f289e9a01f4577cc66d40384ff8"
M3_NEXT_DAY_DIGEST = "fe510d1a807fc7789c7521395b64969a35c89c416e1c40ad9ffda3fc598356a3"


def m3_projection_digest(world) -> str:
    """Compare every original field against output generated by frozen M3."""
    document = json.loads(_payload_for(world))
    document["schema_version"] = 2
    for name in ("social_ties", "institutions", "institutional_rules", "support_duties", "obligations"):
        del document["world"]["fields"][name]
    for _key, household in document["world"]["fields"]["households"]["items"]:
        del household["fields"]["arrangement"]
    payload = json.dumps(document, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    return hashlib.sha256(payload).hexdigest()


class CommunitySchemaTests(unittest.TestCase):
    def test_situated_fixture_uses_existing_people_resources_and_places(self) -> None:
        world = build_community_world(seed=72).world
        self.assertEqual(len(world.institutions), 2)
        self.assertEqual(len(world.social_ties), 4)
        self.assertEqual(len(world.institutional_rules), 2)
        members = set()
        for institution in world.institutions.values():
            for actor_id in institution.member_actor_ids:
                self.assertEqual(world.actors[actor_id].location_id, institution.place_id)
                members.add(actor_id)
            self.assertIn(institution.inventory_holder_id, world.places)
            self.assertIn(institution.cash_holder_id, world.actors)
            self.assertEqual(institution.provenance.confidence, "reconstructed")
        self.assertEqual(len(members), 6)
        self.assertEqual(validate_world(world), [])

    def test_invalid_records_reject_without_mutations(self) -> None:
        world = build_community_world(seed=73).world
        tie = next(iter(world.social_ties.values()))
        institution = world.institutions["trinity-community"]
        rule = next(iter(world.institutional_rules.values()))
        candidates = (
            tie,
            replace(tie, id=institution.id),
            replace(tie, id="merchant"),
            replace(tie, id="unknown-actor", actor_b_id="nobody"),
            replace(tie, id="self-tie", actor_b_id=tie.actor_a_id),
            replace(tie, id="unknown-evidence", evidence_event_ids=("event-nonexistent",)),
            replace(tie, id="backward-time", ends_at=tie.starts_at - timedelta(hours=1)),
            replace(tie, id="unsupported-history", provenance=replace(tie.provenance, confidence="certain")),
            replace(institution, id="missing-site", place_id="nowhere"),
            replace(institution, id="duplicate-members", member_actor_ids=("citizen-0", "citizen-0")),
            replace(institution, id="invalid-official", official_actor_ids=("merchant",)),
            replace(institution, id="negative-capacity", capacity=-1),
            replace(institution, id="moving-storage", inventory_holder_id="merchant"),
            replace(rule, id="orphan-rule", institution_id="absent"),
            replace(rule, id="unsupported-rule", requirement="omniscient_truth"),
            replace(rule, id="beyond-institution", ends_at=institution.ends_at + timedelta(days=1)),
        )
        for candidate in candidates:
            with self.subTest(candidate=candidate.id):
                before = _payload_for(world)
                with self.assertRaises(ValueError):
                    world.add(candidate)
                self.assertEqual(_payload_for(world), before)

    def test_roster_changes_are_validated_and_idempotent(self) -> None:
        world = build_community_world(seed=74).world
        before = _payload_for(world)
        for members, officials in (
            (("citizen-0", "nobody"), ("citizen-0",)),
            (("citizen-0", "citizen-0"), ("citizen-0",)),
            (("citizen-0",), ("citizen-5",)),
        ):
            with self.assertRaises(ValueError):
                set_institution_members(world, "trinity-community", members, officials)
            self.assertEqual(_payload_for(world), before)
        updated = set_institution_members(world, "trinity-community", ("citizen-0", "citizen-2"), ("citizen-2",))
        after = _payload_for(world)
        set_institution_members(world, updated.id, updated.member_actor_ids, updated.official_actor_ids)
        self.assertEqual(_payload_for(world), after)
        self.assertEqual(world.events[-1].kind, "institution_roster_changed")

    def test_generated_ids_and_later_ordinary_collisions_reject_atomically(self) -> None:
        world = build_community_world(seed=74).world
        tie = next(iter(world.social_ties.values()))
        before = _payload_for(world)
        for reserved in (
            f"event-{world._event_number + 1}", f"event-{world._event_number + 100}",
            "lot-999", "movement-999", "observation-999", "statement-999",
            f"contract-{world._event_number + 1}", f"shipment-{len(world.shipments) + 1}",
            "reposition-999", "bank-account-999", "bank-loan-999", "holding-999", "trade-999", "policy-999", "claim-999",
        ):
            with self.assertRaisesRegex(ValueError, "reserved"):
                world.add(replace(tie, id=reserved))
            self.assertEqual(_payload_for(world), before)
        with self.assertRaisesRegex(ValueError, "community record"):
            world.add(Actor(tie.id, "Conflicting actor", "shop"))
        self.assertEqual(_payload_for(world), before)

    def test_frozen_m3_snapshot_migrates_without_changing_next_24_hours(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "frozen.sqlite3"
            path.write_bytes(gzip.decompress(FROZEN_M3_FIXTURE.read_bytes()))
            before_file = path.read_bytes()
            world = load_snapshot(path)
            self.assertEqual(path.read_bytes(), before_file)
            self.assertEqual(m3_projection_digest(world), M3_INITIAL_DIGEST)
            self.assertEqual((world.social_ties, world.institutions, world.institutional_rules), ({}, {}, {}))
            self.assertIn("frozen-m3-move", world.runtime["command_ledger"])
            self.assertTrue(world.movements)
            for _ in range(24):
                advance_world(world, 1)
            self.assertEqual(m3_projection_digest(world), M3_NEXT_DAY_DIGEST)
            self.assertEqual(len(world.events), 964)
            self.assertEqual(validate_world(world), [])
            info = save_snapshot(world, path)
            self.assertEqual(info.schema_version, SNAPSHOT_SCHEMA_VERSION)
            self.assertEqual(_payload_for(load_snapshot(path)), _payload_for(world))

    def test_community_replay_round_trip_preserves_all_state(self) -> None:
        uninterrupted = build_community_world(seed=75).world
        resumed = copy.deepcopy(uninterrupted)
        for _ in range(12):
            advance_world(uninterrupted, 1)
            advance_world(resumed, 1)
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "community.sqlite3"
            save_snapshot(resumed, path)
            resumed = load_snapshot(path)
        for _ in range(12):
            advance_world(uninterrupted, 1)
            advance_world(resumed, 1)
        self.assertEqual(_payload_for(resumed), _payload_for(uninterrupted))
        self.assertEqual(validate_world(resumed), [])

    def test_invalid_schema3_references_are_rejected_on_load(self) -> None:
        world = build_community_world(seed=76).world
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "invalid.sqlite3"
            save_snapshot(world, path)
            institution = world.institutions["trinity-community"]
            world.institutions[institution.id] = replace(institution, official_actor_ids=("nobody",))
            payload = _payload_for(world)
            with sqlite3.connect(path) as connection:
                connection.execute("UPDATE world_snapshots SET payload = ?, checksum = ?", (
                    payload, hashlib.sha256(payload).hexdigest(),
                ))
            with self.assertRaisesRegex(ValueError, "invalid world"):
                load_snapshot(path)

    def test_migration_rejects_incomplete_frozen_schema_without_rewriting_it(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "incomplete.sqlite3"
            path.write_bytes(gzip.decompress(FROZEN_M3_FIXTURE.read_bytes()))
            with sqlite3.connect(path) as connection:
                raw = connection.execute("SELECT payload FROM world_snapshots").fetchone()[0]
                document = json.loads(raw)
                del document["world"]["fields"]["random"]
                payload = json.dumps(document, sort_keys=True, separators=(",", ":")).encode()
                connection.execute("UPDATE world_snapshots SET payload = ?, checksum = ?", (
                    payload, hashlib.sha256(payload).hexdigest(),
                ))
            before = path.read_bytes()
            with self.assertRaisesRegex(ValueError, "frozen schema 2"):
                load_snapshot(path)
            self.assertEqual(path.read_bytes(), before)


if __name__ == "__main__":
    unittest.main()
